// Service Worker for FVI & Post-Lam Inspection PWA (Network-First for instant repo updates)
const CACHE_NAME = 'usm-inspection-pwa-v1';

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;

  const url = new URL(req.url);
  // Never intercept live API, SSE stream, or EL image requests
  if (url.pathname.startsWith('/api/')) return;

  // Network-first strategy: always pull latest code/UI from Docker server, fall back to cache only if briefly offline
  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res && res.status === 200) {
          const copy = res.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(req, copy)).catch(() => {});
        }
        return res;
      })
      .catch(() => caches.match(req))
  );
});
